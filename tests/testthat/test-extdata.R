test_that("the Foz do Amazonas example tables are complete and read as the app expects", {
  map <- utils::read.csv(system.file("extdata", "foz_ocean_map.csv", package = "depprep"))
  series <- utils::read.csv(system.file("extdata", "foz_ocean_series.csv", package = "depprep"))
  src <- utils::read.csv(system.file("extdata", "foz_ocean_sources.csv", package = "depprep"))
  vars <- c("chl", "par", "poc", "sst", "wind_x")
  expect_identical(names(map), c("x_km", "y_km", "lon", "lat", vars))
  expect_identical(names(series), c("month", "time", vars))
  expect_identical(src$variable, vars)
  expect_false(anyNA(map))
  expect_false(anyNA(series))
  expect_identical(series$time, seq_len(nrow(series)))
  expect_false(anyDuplicated(map[, c("x_km", "y_km")]) > 0)
  # either pair of coordinates; the other pair is not taken as variables
  d <- depprep:::.app_data(map, "spatial", x = "x_km", y = "y_km")
  expect_identical(colnames(d$X), vars)
  expect_length(d$notes, 0)
  d <- depprep:::.app_data(map, "spatial", x = "lon", y = "lat")
  expect_identical(colnames(d$X), vars)
  expect_match(d$notes, "Near the equator this is fine")
  d <- depprep:::.app_data(series, "temporal", time = "time")
  expect_identical(colnames(d$X), vars)
})
